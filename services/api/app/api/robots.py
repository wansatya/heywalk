@router.post(
    "/api/projects/{project_id}/controller/sample",
    response_model=ProjectFileContent,
)
def import_sample_controller(
    project_id: str, body: StarterRobotInstall, request: Request
) -> ProjectFileContent:
    """Write the robot's sample controller and reset to default grading.

    Foundry robots have no authored sample task; they install the platform's
    position-tracking reference controller so joint tests are runnable.
    """
    store: Store = request.app.state.store
    foundry_id = foundry_id_from_robot_id(body.robot_id)
    if foundry_id is not None:
        if store.get_project(project_id) is None:
            raise HTTPException(status_code=404, detail="Project not found.")
        foundry: FoundryStore | None = getattr(request.app.state, "foundry", None)
        if foundry is None or foundry.get_project(foundry_id) is None:
            raise HTTPException(status_code=404, detail="Foundry robot not found.")
        try:
            saved = file_service.save_project_file(
                store, project_id, "controller.py", REFERENCE_CONTROLLER
            )
        except (FilePathError, FileTooLargeError, TooManyFilesError) as exc:
            raise HTTPException(status_code=409, detail=str(exc)) from exc
        store.set_project_objectives(project_id, None)
        return ProjectFileContent(**saved)
    try:
        saved = generation_service.import_sample_controller(
            store, project_id, body.robot_id
        )
    except ProjectNotFoundError as exc:
        raise HTTPException(status_code=404, detail="Project not found.") from exc
    except UnknownStarterRobotError as exc:
        raise HTTPException(status_code=404, detail=str(exc)) from exc
    return ProjectFileContent(**saved)


@router.get("/api/projects/{project_id}/robot")
def installed_robot(project_id: str, request: Request) -> dict:
    """Robot installed in a project, detected by MJCF marker.

    Returns ``{"robot_id": ...}`` with the catalog id, or null when the
    project holds a custom rig (or no model yet). The UI uses this to
    label the current robot and to fetch its 3D model.
    """
    store: Store = request.app.state.store
    if store.get_project(project_id) is None:
        raise HTTPException(status_code=404, detail="Project not found.")
    try:
        entries = store.list_files(project_id)
    except (OSError, KeyError):
        entries = []
    for entry in entries:
        path = str(entry.get("path", ""))
        if not path.lower().endswith(".xml"):
            continue
        stored = store.get_file(project_id, path)
        content = stored["content"] if stored else ""
        if "<mujoco" in content[:4096].lower():
            robot = detect_starter_robot(content)
            if robot is not None:
                return {"robot_id": robot.id}
            foundry = detect_foundry_robot(content)
            if foundry is not None:
                return {"robot_id": foundry.id}
    # Packages generated before the marker was introduced are still linked
    # from the Foundry database; use that link as a migration fallback.
    foundry_store: FoundryStore | None = getattr(request.app.state, "foundry", None)
    if foundry_store is not None:
        linked = foundry_store.get_by_sequence(project_id)
        if linked is not None:
            return {"robot_id": foundry_robot_id(linked["id"])}
    return {"robot_id": None}


@router.post(
    "/api/projects/{project_id}/robot", response_model=RobotPackageOut
)
def install_starter_robot(
    project_id: str, body: StarterRobotInstall, request: Request
) -> RobotPackageOut:
    store: Store = request.app.state.store
    foundry_id = foundry_id_from_robot_id(body.robot_id)
    if foundry_id is not None:
        if store.get_project(project_id) is None:
            raise HTTPException(status_code=404, detail="Project not found.")
        foundry: FoundryStore | None = getattr(request.app.state, "foundry", None)
        if foundry is None or foundry.get_project(foundry_id) is None:
            raise HTTPException(status_code=404, detail="Foundry robot not found.")
        try:
            result = install_foundry_robot(
                store,
                project_id,
                foundry,
                foundry_id,
                include_controller=body.include_controller,
            )
        except (RobotPackageError, ValueError) as exc:
            raise HTTPException(status_code=409, detail=str(exc)) from exc
        except (FilePathError, FileTooLargeError, TooManyFilesError) as exc:
            raise HTTPException(status_code=409, detail=str(exc)) from exc
        return RobotPackageOut(**result)
    try:
        return generation_service.install_starter_robot(
            store, project_id, body.robot_id,
            include_controller=body.include_controller,
        )
    except ProjectNotFoundError as exc:
        raise HTTPException(status_code=404, detail="Project not found.") from exc
    except UnknownStarterRobotError as exc:
        raise HTTPException(status_code=404, detail=str(exc)) from exc
    except RobotPackageError as exc:
        raise HTTPException(
            status_code=500,
            detail=f"Bundled starter robot is not simulatable: {exc}",
        ) from exc
    except (FilePathError, FileTooLargeError, TooManyFilesError) as exc:
        raise HTTPException(status_code=409, detail=str(exc)) from exc
