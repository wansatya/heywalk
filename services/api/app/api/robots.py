def _foundry_robot_summaries(foundry: FoundryStore) -> list[StarterRobotOut]:
    """Catalog entries for Foundry projects with a validated generated model."""
    entries: list[StarterRobotOut] = []
    for project in foundry.list_projects():
        latest = foundry.latest_version(project["id"])
        if latest is None:
            continue
        validation = latest.get("validation") or {}
        if str(validation.get("status") or "").lower() not in ("ok", "warning"):
            continue
        root = foundry.project_dir(project["id"])
        model_path = root / "robot.xml"
        if not model_path.is_file():
            continue
        try:
            xml = model_path.read_text(encoding="utf-8")
            package = build_robot_package({"robot.xml": xml})
            tests = default_tests_for_joints(
                [
                    (joint.name, joint.lower, joint.upper)
                    for joint in package.info.joints
                ]
            )
        except (OSError, UnicodeDecodeError, RobotPackageError, ScenarioError):
            # A broken artifact must not take down the whole catalog.
            continue
        thumbnail = (project.get("thumbnail_url") or "").strip()
        thumbnail_url = (
            f"/api/foundry/projects/{project['id']}/assets/{thumbnail.lstrip('/')}"
            if thumbnail
            else None
        )
        category = project.get("category") or "biped"
        entries.append(
            StarterRobotOut(
                id=foundry_robot_id(project["id"]),
                name=project["name"],
                summary=(
                    f"Foundry-generated {category} robot with"
                    f" {len(package.info.joints)} actuated joints."
                    " Geometry and physics are estimates from reference images."
                ),
                attribution=(
                    "Generated in Robot Foundry. Review the reconstruction and"
                    " estimated physics before relying on it."
                ),
                license="Generated by HeyWalk Robot Foundry",
                source_url="",
                model_path=package.model_path,
                joints=[joint.to_dict() for joint in package.info.joints],
                tests=[test.to_dict() for test in tests],
                source="foundry",
                foundry_id=project["id"],
                thumbnail_asset_url=thumbnail_url,
            )
        )
    return entries


@router.get("/api/robots", response_model=list[StarterRobotOut])
def list_starter_robots(request: Request) -> list[StarterRobotOut]:
    robots = [
        StarterRobotOut(**starter_robot_summary(robot)) for robot in starter_robots()
    ]
    foundry: FoundryStore | None = getattr(request.app.state, "foundry", None)
    if foundry is not None:
        robots.extend(_foundry_robot_summaries(foundry))
    return robots


def _robot_models(request: Request, robot_id: str) -> Any:
    """Model package for a bundled or Foundry robot, or a 404."""
    foundry_id = foundry_id_from_robot_id(robot_id)
    if foundry_id is not None:
        foundry: FoundryStore | None = getattr(request.app.state, "foundry", None)
        if foundry is None or foundry.get_project(foundry_id) is None:
            raise HTTPException(status_code=404, detail="Foundry robot not found.")
        return FoundryRobotModel(foundry, foundry_id)
    try:
        robot = get_starter_robot(robot_id)
    except UnknownStarterRobotError as exc:
        raise HTTPException(status_code=404, detail=str(exc)) from exc
    if robot.models is None:
        raise HTTPException(
            status_code=404,
            detail=f"Starter robot {robot_id!r} has no bundled model.",
        )
    return robot.models


def _robot_model_payload(request: Request, robot_id: str) -> dict:
    """Model metadata + load status for the UI, for any catalog robot.

    Returns joints, actuators, sensors, body hierarchy, physics parameters,
    visual mesh placements, the preview pose, the composed environment (for
    bundled robots), and whether the mesh assets resolve. The 3D view poses
    meshes from live telemetry (or the preview before a run streams).
    """
    is_foundry = foundry_id_from_robot_id(robot_id) is not None
    models = _robot_models(request, robot_id)
    try:
        metadata = models.load_metadata()
        hierarchy = models.body_hierarchy()
        visuals = models.visual_geoms()
        preview = models.stand_poses()
        environment = models.environment_payload()
        missing = models.missing_assets()
    except (RuntimeError, ValueError) as exc:
        raise HTTPException(
            status_code=409 if is_foundry else 500, detail=str(exc)
        ) from exc
    payload = metadata.to_dict()
    payload["robot_id"] = robot_id
    payload["hierarchy"] = hierarchy
    payload["visual_geoms"] = visuals
    payload["default_poses"] = preview
    payload["environment"] = environment
    payload["assets_ok"] = not missing
    payload["missing_assets"] = list(missing)
    if missing:
        payload["error"] = (
            f"{len(missing)} mesh asset(s) are missing from the robot package;"
            " regenerate the robot or reinstall the application."
        )
    return payload


def _robot_asset_bundle(request: Request, robot_id: str) -> Response:
    """Serve every mesh the 3D view needs as one response.

    Fetching dozens of STLs one by one costs dozens of round trips, which
    dominates simulator load time on high-latency links. The bundle
    carries the same bytes with one round trip and slightly better gzip
    (one stream).

    Framing: u32 little-endian manifest length, then the manifest JSON
    (``[{"name": ..., "size": ...}]`` in blob order), then the raw file
    bytes concatenated.
    """
    import json
    import struct

    is_foundry = foundry_id_from_robot_id(robot_id) is not None
    models = _robot_models(request, robot_id)
    try:
        names = sorted({entry["file"] for entry in models.visual_geoms()})
        blobs = [models.resolve_asset(name).read_bytes() for name in names]
    except (RuntimeError, ValueError) as exc:
        raise HTTPException(
            status_code=404 if is_foundry else 500, detail=str(exc)
        ) from exc
    manifest = json.dumps(
        [{"name": name, "size": len(blob)} for name, blob in zip(names, blobs)]
    ).encode("utf-8")
    body = struct.pack("<I", len(manifest)) + manifest + b"".join(blobs)
    return Response(
        content=body,
        media_type="application/octet-stream",
        headers={
            "Cache-Control": "public, max-age=60" if is_foundry else "public, max-age=86400"
        },
    )


def _robot_asset(request: Request, robot_id: str, filename: str) -> FileResponse:
    """Serve one robot mesh (STL) to the 3D view.

    Only mesh files the model references are served; anything else is a 404,
    so this endpoint can never leak arbitrary host files.
    """
    is_foundry = foundry_id_from_robot_id(robot_id) is not None
    models = _robot_models(request, robot_id)
    try:
        path = models.resolve_asset(filename)
    except (RuntimeError, ValueError) as exc:
        raise HTTPException(status_code=404, detail=str(exc)) from exc
    # Bundled meshes are stable per release, so let browsers cache them:
    # without this every simulator load re-downloads all meshes,
    # saturating the browser's per-origin connection pool and starving
    # API calls behind the bulk download on slow links. Foundry packages can
    # be regenerated, so they get a short cache window instead.
    return FileResponse(
        path,
        media_type="model/stl",
        filename=filename,
        headers={
            "Cache-Control": "public, max-age=60" if is_foundry else "public, max-age=86400"
        },
    )


