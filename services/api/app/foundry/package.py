"""Package + export stage.

Two outputs are produced from the same artifacts:

1. The Foundry artifact folder (``<foundry_root>/<foundry_id>/``) holds the
   full generated package plus the original references and per-component
   source/mask files.
2. The linked sequence folder holds the files the existing simulator reads
   (``robot.xml``, ``robot.urdf``, ``ros2_control.yaml``, a controller, and
   the binary meshes). Text files are also saved through the normal project
   file store so the IDE editor can open them.
"""

from __future__ import annotations

import io
import json
import shutil
import zipfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from ..db import Store
from ..simulator.foundry_robot import stamp_foundry_marker
from ..simulator.robot_catalog import REFERENCE_CONTROLLER
from ..simulator.robot_description import build_robot_package
from ..simulator.scenario import default_tests_for_joints
from .store import FoundryStore, slug
from .template_microduck import TEMPLATE_VERSION

PACKAGE_TEXT_FILES = (
    "robot.xml",
    "robot.urdf",
    "ros2_control.yaml",
    "manifest.json",
    "README.md",
    "config/physics.json",
    "config/joints.json",
    "config/actuators.json",
    "validation/validation.json",
    "scenes/test_world.xml",
    "controllers/controller.py",
)

#: Extensions that must be copied as binary (the project file store only
#: mirrors UTF-8 text).
BINARY_EXTENSIONS = {".obj", ".stl", ".glb", ".gltf", ".png", ".jpg", ".jpeg", ".webp"}


def _write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def _readme(project: dict[str, Any], validation: dict[str, Any]) -> str:
    lines = [
        f"# {project['name']}",
        "",
        f"Generated by HeyWalk Robot Foundry from {project.get('category', 'biped')} reference images.",
        "",
        "## What this package is",
        "",
        "- `robot.xml`: MuJoCo MJCF model, compilable by MuJoCo.",
        "- `assets/visual/`: visual OBJ meshes reconstructed from visible parts.",
        "- `assets/collision/`: separate collision STL meshes.",
        "- `config/`: joints, actuators, and estimated physics.",
        "- `validation/validation.json`: the actual checks that were run.",
        "- `controllers/controller.py`: platform starter controller (position tracking).",
        "",
        "Simulation contract (actuator tuning, IMU sensors, STAND keyframe)",
        "follows the official MicroDuck model by Pollen Robotics (Apache-2.0",
        "MJCF); meshes are generated from the user's reference images.",
        "",
        "## Honest limitations",
        "",
        "- A single image cannot reveal depth, hidden surfaces, or the real internal mechanism.",
        "- Mass and inertia values are estimates, not measurements.",
        "- The articulated hierarchy is inferred from the visible layout.",
        "- A compiling model is not guaranteed to be dynamically stable.",
        "",
        f"Validation status: **{validation.get('status', 'unknown')}**",
        "",
    ]
    warnings = validation.get("warnings") or []
    if warnings:
        lines.append("### Warnings")
        lines.extend(f"- {warning}" for warning in warnings)
        lines.append("")
    errors = validation.get("errors") or []
    if errors:
        lines.append("### Errors")
        lines.extend(f"- {error}" for error in errors)
        lines.append("")
    return "\n".join(lines)


def _test_world() -> str:
    return """<?xml version="1.0"?>
<!-- HeyWalk test world. Load robot.xml directly for the joint-test scenario. -->
<mujoco model="foundry_test_world">
  <include file="../robot.xml"/>
  <option timestep="0.005"/>
</mujoco>
"""


def build_package_files(
    *,
    foundry_project: dict[str, Any],
    components: list[dict[str, Any]],
    joints: list[dict[str, Any]],
    actuators: list[dict[str, Any]],
    xml: str,
    validation: dict[str, Any],
    version: int | None = None,
) -> dict[str, str]:
    """Return every text file of the package, keyed by package-relative path."""
    package = build_robot_package({"robot.xml": xml})
    manifest = {
        "foundry_project_id": foundry_project["id"],
        "sequence_project_id": foundry_project.get("project_id") or None,
        "name": foundry_project["name"],
        "category": foundry_project.get("category", "biped"),
        "version": version,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "generator": "heywalk-foundry",
        "simulation_contract": TEMPLATE_VERSION,
        "model_path": "robot.xml",
        "components": [
            {
                "id": component["id"],
                "name": component["name"],
                "label": component["label"],
                "type": component["component_type"],
                "parent_id": component.get("parent_id"),
                "mesh_url": component.get("mesh_url"),
                "collision_mesh_url": component.get("collision_mesh_url"),
                "confidence": component.get("confidence"),
            }
            for component in components
        ],
        "joints": joints,
        "actuators": actuators,
        "validation_status": validation.get("status"),
        "notes": [
            "Geometry is reconstructed from visible parts; hidden geometry is not invented.",
            "Physics values are estimates and are marked as such.",
        ],
    }
    files = {
        "robot.xml": package.files["robot.xml"],
        "robot.urdf": package.files.get("robot.urdf", ""),
        "ros2_control.yaml": package.files.get("ros2_control.yaml", ""),
        "manifest.json": json.dumps(manifest, indent=2),
        "README.md": _readme(foundry_project, validation),
        "config/physics.json": json.dumps(
            [
                {
                    "component_id": component["id"],
                    "name": component["name"],
                    "physics": (component.get("metadata") or {}).get("physics", {}),
                }
                for component in components
            ],
            indent=2,
        ),
        "config/joints.json": json.dumps(joints, indent=2),
        "config/actuators.json": json.dumps(actuators, indent=2),
        "validation/validation.json": json.dumps(validation, indent=2),
        "scenes/test_world.xml": _test_world(),
        "controllers/controller.py": REFERENCE_CONTROLLER,
    }
    return files


def write_artifacts(
    foundry_store: FoundryStore,
    foundry_id: str,
    files: dict[str, str],
) -> None:
    root = foundry_store.project_dir(foundry_id)
    for relative, content in files.items():
        _write(root / relative, content)


def copy_to_sequence(
    sequence_store: Store,
    sequence_id: str,
    foundry_store: FoundryStore,
    foundry_id: str,
    files: dict[str, str],
    *,
    overwrite_controller: bool = False,
    skip_prefixes: tuple[str, ...] = ("components",),
) -> dict[str, Any]:
    """Copy the package into the linked sequence.

    Text files are written through ``Store.save_file`` (so the IDE sees them
    and they survive a missing disk file). Binary meshes and reference images
    are copied directly because the project file store only mirrors text.
    ``skip_prefixes`` drops artifact-only folders (per-component review
    sources, reference images) when installing into another sequence.
    """
    sequence_dir = sequence_store.project_dir(sequence_id)
    foundry_dir = foundry_store.project_dir(foundry_id)
    saved_text: list[str] = []
    for relative, content in files.items():
        if relative == "controllers/controller.py":
            target = sequence_dir / "controller.py"
            if target.exists() and not overwrite_controller:
                continue
            # The simulator executes controller.py at the workspace root.
            sequence_store.save_file(sequence_id, "controller.py", content)
            saved_text.append("controller.py")
            continue
        sequence_store.save_file(sequence_id, relative, content)
        saved_text.append(relative)

    copied_binary: list[str] = []
    for source in sorted(foundry_dir.rglob("*")):
        if not source.is_file() or source.is_symlink():
            continue
        relative = source.relative_to(foundry_dir)
        if relative.parts and relative.parts[0] in skip_prefixes:
            continue
        if relative.as_posix() in files:
            continue
        if source.suffix.lower() not in BINARY_EXTENSIONS:
            continue
        target = sequence_dir / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target)
        copied_binary.append(relative.as_posix())

    return {
        "project_id": sequence_id,
        "text_files": saved_text,
        "binary_files": copied_binary,
    }


def package_files_from_artifacts(
    foundry_store: FoundryStore, foundry_id: str
) -> dict[str, str]:
    """Load the text package from a Foundry artifact folder.

    Existing files win; missing companions are synthesized from the MJCF, so
    a package generated by an older build still installs cleanly.
    """
    root = foundry_store.project_dir(foundry_id)
    files: dict[str, str] = {}
    for relative in PACKAGE_TEXT_FILES:
        path = root / relative
        if not path.is_file():
            continue
        try:
            files[relative] = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
    xml = files.get("robot.xml")
    if not xml:
        raise ValueError(
            "This Foundry robot has no generated robot.xml yet. Run the MJCF"
            " stage before installing it into a sequence."
        )
    xml = stamp_foundry_marker(xml, foundry_id)
    files["robot.xml"] = xml
    package = build_robot_package(files)
    for path, content in package.files.items():
        files.setdefault(path, content)
    files.setdefault("controllers/controller.py", REFERENCE_CONTROLLER)
    return files


def install_foundry_robot(
    sequence_store: Store,
    sequence_id: str,
    foundry_store: FoundryStore,
    foundry_id: str,
    *,
    include_controller: bool = False,
    return_copy: bool = False,
) -> dict[str, Any]:
    """Install a generated Foundry robot into an arbitrary sequence.

    Mirrors ``install_starter_robot``: the robot model and companions are
    written, but a user's ``controller.py`` is left untouched unless the
    caller explicitly asks for the reference controller.
    """
    files = package_files_from_artifacts(foundry_store, foundry_id)
    package = build_robot_package(files)
    if not include_controller:
        files.pop("controllers/controller.py", None)
    copied = copy_to_sequence(
        sequence_store,
        sequence_id,
        foundry_store,
        foundry_id,
        files,
        overwrite_controller=include_controller,
        skip_prefixes=("components", "images"),
    )
    if not include_controller and sequence_store.get_file(
        sequence_id, "controller.py"
    ) is None:
        sequence_store.save_file(sequence_id, "controller.py", "")
    tests = default_tests_for_joints(
        [(joint.name, joint.lower, joint.upper) for joint in package.info.joints]
    )
    result = {
        "model_path": package.model_path,
        "joints": [joint.to_dict() for joint in package.info.joints],
        "tests": [test.to_dict() for test in tests],
        "notes": list(package.notes),
    }
    if return_copy:
        result.update(copied)
    return result


def package_zip(foundry_store: FoundryStore, foundry_id: str) -> bytes:
    """Zip the full Foundry artifact folder (references, meshes, configs)."""
    root = foundry_store.project_dir(foundry_id)
    buffer = io.BytesIO()
    total = 0
    limit = 128 * 1024 * 1024
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        for path in sorted(root.rglob("*")):
            if not path.is_file() or path.is_symlink():
                continue
            relative = path.relative_to(root).as_posix()
            total += path.stat().st_size
            if total > limit:
                raise ValueError("Foundry package exceeds the 128 MiB export limit.")
            archive.write(path, relative)
    return buffer.getvalue()


def package_name(project: dict[str, Any]) -> str:
    return slug(project.get("name") or "robot", "robot")


